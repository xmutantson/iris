/*
 * gen_winlink_dict — build-time generator for source/compress/winlink_dict.cc (Iris).
 *
 * Reads the raw dictionary plaintext (tools/winlink_dict_v1.txt), compresses it with
 * the PRODUCTION iris::Compressor on a fresh streaming context, and emits a C++
 * translation unit baking in:
 *   - WINLINK_DICT_RAW[]        : the raw dictionary bytes (+ NUL)
 *   - WINLINK_DICT_RAW_LEN      : raw length (excludes NUL)
 *   - WINLINK_DICT_COMPRESSED[] : the canonical streaming-compressed form of RAW
 *   - WINLINK_DICT_COMPRESSED_LEN
 *
 * The compressed blob is what Compressor::prime_with_dict() decompresses on BOTH peers
 * to warm the PPMd model identically (role-independent priming). It is generated by the
 * SAME Compressor the firmware runs, so a firmware that links this .cc is guaranteed
 * self-consistent: decompress(COMPRESSED) == RAW.
 *
 * PRE-SHIP: no wire version bit. Regenerate this .cc and rebuild BOTH ends whenever the
 * raw dict changes.
 *
 * Usage: gen_winlink_dict <raw_dict.txt> <out_winlink_dict.cc>
 * BUILD-TIME tool. The emitted .cc is checked in.
 */
#include "compress/compress.h"
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

int main(int argc, char** argv)
{
    if (argc < 3) { fprintf(stderr, "usage: %s <raw_dict.txt> <out.cc>\n", argv[0]); return 2; }

    FILE* f = fopen(argv[1], "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", argv[1]); return 2; }
    fseek(f, 0, SEEK_END); long sz = ftell(f); rewind(f);
    std::string raw((size_t)sz, 0);
    if (sz > 0 && fread(&raw[0], 1, sz, f) != (size_t)sz) { fclose(f); return 2; }
    fclose(f);

    // Compress RAW with the production compressor on a FRESH, UN-PRIMED stream — exactly
    // the first batch of an empty streaming context. This is what the firmware's
    // prime_with_dict() decompresses to warm the model, and it runs on a brand-new
    // (not-yet-primed) stream, so the canonical COMPRESSED blob MUST be produced on an
    // un-primed stream too. set_dict_priming(false) is REQUIRED here: if priming were
    // left on, streaming_enable() would seed this context with the PREVIOUSLY-baked dict
    // before compressing, and the resulting blob would only round-trip against an
    // identically-primed RX — never the firmware's fresh prime path.
    iris::Compressor c; c.set_dict_priming(false); c.init(); c.streaming_enable();
    std::vector<uint8_t> in((const uint8_t*)raw.data(), (const uint8_t*)raw.data() + raw.size());
    std::vector<uint8_t> out(raw.size() * 2 + 4096);
    int w = c.compress_block(in.data(), (int)in.size(), out.data(), (int)out.size());
    if (w <= 0) { fprintf(stderr, "compress_block failed (%d)\n", w); c.deinit(); return 1; }

    // Self-check: a fresh, UN-PRIMED RX decompresses COMPRESSED back to RAW bit-exact —
    // mirroring the firmware's prime_with_dict() which decodes the blob on a brand-new
    // (not-yet-primed) stream.
    iris::Compressor rx; rx.set_dict_priming(false); rx.init(); rx.streaming_enable();
    std::vector<uint8_t> back(raw.size() + 4096);
    int d = rx.decompress_block(out.data(), w, back.data(), (int)back.size());
    bool ok = (d == (int)raw.size() && memcmp(back.data(), raw.data(), raw.size()) == 0);
    rx.deinit();
    if (!ok) { fprintf(stderr, "SELF-CHECK FAILED: decompress(COMPRESSED) != RAW (d=%d raw=%zu)\n", d, raw.size()); c.deinit(); return 1; }

    int algo = out[0] & iris::COMPRESS_ALGO_MASK;

    FILE* o = fopen(argv[2], "wb");
    if (!o) { fprintf(stderr, "cannot write %s\n", argv[2]); c.deinit(); return 2; }
    fprintf(o,
        "/* GENERATED by tools/gen_winlink_dict.cc — DO NOT EDIT BY HAND.\n"
        " * Source: %s  raw_len=%zu  compressed_len=%d  algo=%s\n"
        " * Regenerate (tools/gen_winlink_dict.cc) and rebuild BOTH ends when the raw\n"
        " * dict changes. PRE-SHIP: no wire version bit. */\n"
        "#include \"compress/winlink_dict.h\"\n\n",
        argv[1], raw.size(), w, algo == iris::COMPRESS_ALGO_PPMD ? "PPMd" :
                                 algo == iris::COMPRESS_ALGO_ZSTD ? "zstd" : "raw");

    // RAW
    fprintf(o, "const char WINLINK_DICT_RAW[] =\n");
    fputc('"', o);
    for (size_t i = 0; i < raw.size(); i++) {
        unsigned char ch = (unsigned char)raw[i];
        if (ch == '\n') fputs("\\n", o);
        else if (ch == '\r') fputs("\\r", o);
        else if (ch == '\t') fputs("\\t", o);
        else if (ch == '"')  fputs("\\\"", o);
        else if (ch == '\\') fputs("\\\\", o);
        else if (ch >= 0x20 && ch < 0x7f) fputc(ch, o);
        else fprintf(o, "\\x%02x\"\"", ch); /* "" guards hex-run termination */
        if ((i & 31) == 31) fputs("\"\n\"", o);
    }
    fputs("\";\n", o);
    fprintf(o, "const unsigned int WINLINK_DICT_RAW_LEN = %zuu;\n\n", raw.size());

    // COMPRESSED
    fprintf(o, "const unsigned char WINLINK_DICT_COMPRESSED[] = {\n");
    for (int i = 0; i < w; i++) {
        fprintf(o, "0x%02x,", (unsigned char)out[i]);
        if ((i & 15) == 15) fputc('\n', o);
    }
    fprintf(o, "\n};\n");
    fprintf(o, "const unsigned int WINLINK_DICT_COMPRESSED_LEN = %du;\n", w);
    fclose(o);
    c.deinit();

    fprintf(stderr, "OK raw_len=%zu compressed_len=%d algo=%d self_check=PASS -> %s\n",
            raw.size(), w, algo, argv[2]);
    return 0;
}
